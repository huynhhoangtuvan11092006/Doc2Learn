"""Hallucination detection module for Doc2Learn evaluation.

Verifies technical entities, numeric facts, and domain constants
in generated outputs against the ground truth reference context
to ensure factual consistency and prevent hallucinated figures.
"""

from __future__ import annotations

import re
from typing import Any, Dict, List, Set


# Regex pattern to capture technical facts:
# 1. Numbers with optional units: e.g., 2.5V, 1.5 V, 11-bit, 1 Mbps, 120 ohm, 255 TEC, 500kbps, 0x7FF
# 2. Hex values and standalone numbers: 0x123, 255, 11, 29
# 3. Capitalized technical acronyms / identifiers: CAN, CSMA/CD, SOF, EOF, CRC, ACK, DLC
NUMERIC_UNIT_PATTERN = re.compile(
    r"\b\d+(?:\.\d+)?\s*(?:[vV]|mV|kV|bit|bits|bps|kbps|Mbps|Gbps|ohm|k\u03a9|byte|bytes|TEC|REC|ms|us|ns|%|MHz|kHz)?\b"
)
HEX_PATTERN = re.compile(r"\b0x[0-9a-fA-F]+\b")
ACRONYM_PATTERN = re.compile(r"\b[A-Z]{2,}(?:/[A-Z0-9]+)?\b")


def extract_technical_entities(text: str) -> Set[str]:
    """Extract factual technical entities (numbers with units, hex codes, acronyms) from text.

    Args:
        text: Input text string (question, summary, or source context).

    Returns:
        Set of normalized entity strings.
    """
    if not text:
        return set()

    entities: Set[str] = set()

    # Extract numbers with units
    for match in NUMERIC_UNIT_PATTERN.finditer(text):
        val = match.group().strip()
        # Filter out trivial single digits without units unless relevant
        if val:
            # Normalize whitespace: '2.5 V' -> '2.5v'
            normalized = re.sub(r"\s+", "", val).lower()
            entities.add(normalized)

    # Extract hex codes
    for match in HEX_PATTERN.finditer(text):
        entities.add(match.group().strip().lower())

    # Extract technical acronyms (at least 2 letters, e.g., CAN, CRC, ACK, SOF)
    for match in ACRONYM_PATTERN.finditer(text):
        acronym = match.group().strip().upper()
        # Exclude common non-technical English words in uppercase
        if acronym not in {"THE", "AND", "FOR", "WITH", "THAT", "THIS", "NOT", "ARE", "HAS"}:
            entities.add(acronym)

    return entities


def check_hallucination(
    generated_text: str, source_context: str
) -> Dict[str, Any]:
    """Check whether technical entities in generated output exist in source context.

    Args:
        generated_text: Output generated by the model (quiz, explanation, summary).
        source_context: The reference chunk/context from the technical document.

    Returns:
        Dict containing:
            - total_entities: Number of technical facts claimed by the model.
            - grounded_entities: Entities verified in the source context.
            - hallucinated_entities: Entities claimed by the model but absent from context.
            - hallucination_rate: Ratio of hallucinated to total entities (0.0 to 1.0).
            - is_hallucinated: True if hallucination_rate exceeds 0.20 (20%).
    """
    gen_entities = extract_technical_entities(generated_text)
    src_entities = extract_technical_entities(source_context)

    # Context full normalized text for direct substring checking as fallback
    norm_context = re.sub(r"\s+", "", source_context).lower()

    grounded: List[str] = []
    hallucinated: List[str] = []

    for ent in gen_entities:
        clean_ent = ent.lower()
        if ent in src_entities or clean_ent in norm_context:
            grounded.append(ent)
        else:
            # Check if stripped of non-alphanumeric exists
            raw_val = re.sub(r"[^\w]", "", clean_ent)
            if raw_val and raw_val in norm_context:
                grounded.append(ent)
            else:
                hallucinated.append(ent)

    total = len(gen_entities)
    hallucination_rate = len(hallucinated) / total if total > 0 else 0.0

    return {
        "total_entities": total,
        "grounded_count": len(grounded),
        "hallucinated_count": len(hallucinated),
        "grounded_entities": sorted(grounded),
        "hallucinated_entities": sorted(hallucinated),
        "hallucination_rate": round(hallucination_rate, 4),
        "is_hallucinated": hallucination_rate > 0.20,
    }


def batch_check_hallucination(
    predictions: List[str], contexts: List[str]
) -> Dict[str, Any]:
    """Check hallucination rates across a batch of generated outputs against their contexts.

    Args:
        predictions: List of model outputs.
        contexts: List of corresponding source document chunks.

    Returns:
        Aggregated summary dict with average hallucination rate.
    """
    if not predictions or not contexts or len(predictions) != len(contexts):
        return {
            "average_hallucination_rate": 0.0,
            "total_samples": 0,
            "hallucinated_samples_count": 0,
            "details": [],
        }

    details = []
    total_rate = 0.0
    hallucinated_samples = 0

    for pred, ctx in zip(predictions, contexts):
        res = check_hallucination(pred, ctx)
        details.append(res)
        total_rate += res["hallucination_rate"]
        if res["is_hallucinated"]:
            hallucinated_samples += 1

    n = len(predictions)
    avg_rate = total_rate / n if n > 0 else 0.0

    return {
        "average_hallucination_rate": round(avg_rate, 4),
        "total_samples": n,
        "hallucinated_samples_count": hallucinated_samples,
        "clean_samples_count": n - hallucinated_samples,
        "details": details,
    }

